"""Render an anonymous Springer working copy from the named author-year source."""
from pathlib import Path
import re


def render(directory):
    directory=Path(directory)
    source=(directory/'main_itt.tex').read_text()
    title=re.search(r'\\title\{([^\n]+)\}',source).group(1)
    abstract=source.split(r'\begin{abstract}',1)[1].split(r'\end{abstract}',1)[0].strip()
    keywords=source.split(r'\begin{keyword}',1)[1].split(r'\end{keyword}',1)[0].strip().replace(r'\sep',',')
    body=source[source.index(r'\section{Introduction}'):source.index(r'\section*{Statements and Declarations}')]
    data=source.split(r'\subsection*{Data and code availability}',1)[1].split(r'\subsection*{Use of AI-assisted tools}',1)[0].strip()
    ai=source.split(r'\subsection*{Use of AI-assisted tools}',1)[1].split(r'\bibliographystyle',1)[0].strip()
    anonymous=r'''% Generated by research.render_springer_manuscript. Edit main_itt.tex.
% Working scientific draft; outstanding results are not supplied by rendering.
\documentclass[pdflatex,sn-basic]{sn-jnl}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{lmodern}
\usepackage{amsmath,amssymb,amsfonts}
\usepackage{graphicx,booktabs,array,tabularx}
\usepackage{microtype,xurl,tikz}
\usetikzlibrary{arrows.meta,positioning,fit}
\setlength{\emergencystretch}{2em}
\hypersetup{hidelinks,pdfauthor={},pdftitle={TITLE}}
\begin{document}
\title{TITLE}
\author{Anonymous for review}
\abstract{ABSTRACT}
\keywords{KEYWORDS}
\maketitle
'''.replace('TITLE',title).replace('ABSTRACT',abstract).replace('KEYWORDS',keywords)
    anonymous+=body+'\n'+r'\section*{Statements and Declarations}'+'\n'
    anonymous+=r'\subsection*{Data and code availability}'+'\n'+data+'\n'
    anonymous+=r'\subsection*{Use of AI-assisted tools}'+'\n'+ai+'\n'
    anonymous+=r'\bibliography{references}'+'\n'+r'\end{document}'+'\n'
    for identity in ('Tran An Khang','Ly Hai Anh','FPT University','khangtran.mschcm@gmail.com'):
        if identity.lower() in anonymous.lower():
            raise ValueError('Author identity in anonymous source: '+identity)
    (directory/'main_itt_anonymous.tex').write_text(anonymous)
    declarations=source.split(r'\section*{Statements and Declarations}',1)[1].split(r'\subsection*{Data and code availability}',1)[0]
    title_page=r'''\documentclass[12pt]{article}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{lmodern}
\usepackage[margin=2.5cm]{geometry}
\usepackage[hidelinks]{hyperref}
\title{TITLE}
\author{Tran An Khang\thanks{Corresponding author: \href{mailto:khangtran.mschcm@gmail.com}{khangtran.mschcm@gmail.com}} \and Ly Hai Anh}
\date{}
\begin{document}
\maketitle
\begin{center}FPT University, Ho Chi Minh City, Vietnam\end{center}
\section*{Statements and Declarations}
DECLARATIONS
\end{document}
'''.replace('TITLE',title).replace('DECLARATIONS',declarations)
    (directory/'title_page.tex').write_text(title_page)


if __name__=='__main__':
    render(Path(__file__).resolve().parents[1]/'manuscript')
